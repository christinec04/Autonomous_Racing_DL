"""How each controller uses the grip: g-g diagrams (nominal races) for PID+APF, PPO + our shield and the final
residual controller, annotated with the share of time cornering hard and braking/accelerating hard.

Shows why the "time above 90% of mu g" target is a poor proxy: plain PPO reaches it with a sawtooth throttle
(hard braking and acceleration), while the faster residual controller corners harder and brakes less.
-> results/grip_use.png, report/figs/grip_use.pdf, results/grip_use.md
"""
import json
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

MG = 1.0489 * 9.81
INK, MUTED, GRID, DOT = "#0b0b0b", "#52514e", "#d9d8d4", "#2a78d6"
PANELS = [
    ("PID + APF", {"results/final_v2_others.json": ["pid_apf"]}),
    ("PPO + our shield", {"results/eval_recover.json": ["ppo_apf_rec@s0", "ppo_apf_rec@s1", "ppo_apf_rec@s2"]}),
    ("Residual + our shield", {"results/eval_residual_shield_s0.json": ["ppo_residual_apf_rec@trained"],
                               "results/eval_residual_shield_s1.json": ["ppo_residual_apf_rec@trained_s1"],
                               "results/eval_residual_shield_s2.json": ["ppo_residual_apf_rec@trained_s2"]}),
    ("PPO + additive APF", {"results/final_v2_others.json": ["ppo_additive"]}),
]


def load(spec):
    races = [r for f, cs in spec.items() for r in json.load(open(f))["races"] if r["controller"] in cs and not r["randomize"]]
    lat = np.concatenate([r["gg"][0] for r in races]) / MG
    lon = np.concatenate([r["gg"][1] for r in races]) / MG
    laps = [t for r in races for t in r["lap_times"][1:]]
    return lat, lon, float(np.mean(laps))


def stats(lat, lon):
    return dict(corner=float(np.mean(np.abs(lat) > 0.6)), brake=float(np.mean(lon < -0.5)),
                accel=float(np.mean(lon > 0.5)), above90=float(np.mean(np.hypot(lat, lon) > 0.9)),
                mean_lat=float(np.mean(np.abs(lat))))


def main():
    data = [(name, *load(spec)) for name, spec in PANELS]
    md = ["# Grip use by controller (nominal races, all training seeds pooled)", "",
          "Generated by `python -m scripts.plot_grip`. g = mu g (1.0489 x 9.81 m/s^2).", "",
          "| controller | clean lap (s) | time > 90% grip | cornering > 0.6 g | braking > 0.5 g | accelerating > 0.5 g | mean lateral |",
          "|---|---|---|---|---|---|---|"]
    for name, lat, lon, lap in data:
        s = stats(lat, lon)
        md.append(f"| {name} | {lap:.1f} | {s['above90']:.0%} | {s['corner']:.0%} | {s['brake']:.0%} | {s['accel']:.0%} | "
                  f"{s['mean_lat']:.2f} |")
    open("results/grip_use.md", "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("\n".join(md))

    show = data[:3]
    plt.rcParams.update({"font.size": 7, "font.family": "serif"})
    fig, axes = plt.subplots(1, len(show), figsize=(3.5, 1.55), sharex=True, sharey=True)
    th = np.linspace(0, 2 * np.pi, 200)
    rng = np.random.default_rng(0)
    for ax, (name, lat, lon, lap) in zip(axes, show):
        idx = rng.choice(len(lat), min(len(lat), 6000), replace=False)  # same point budget per panel
        ax.scatter(lat[idx], lon[idx], s=0.6, color=DOT, alpha=0.25, linewidths=0, rasterized=True)
        ax.plot(np.cos(th), np.sin(th), color=INK, lw=0.6)
        ax.axhline(0, color=GRID, lw=0.4, zorder=0); ax.axvline(0, color=GRID, lw=0.4, zorder=0)
        for x in (-0.6, 0.6):
            ax.axvline(x, color=MUTED, lw=0.4, ls=":", zorder=0)
        ax.axhline(-0.5, color=MUTED, lw=0.4, ls=":", zorder=0)
        s = stats(lat, lon)
        ax.set_title(f"{name}\n{lap:.1f} s lap", fontsize=6.5, color=INK, pad=2)
        ax.text(0.0, -1.28, f"corner {s['corner']:.0%}  brake {s['brake']:.0%}", ha="center", va="bottom",
                fontsize=5.5, color=INK)
        ax.set_aspect("equal"); ax.set_xlim(-1.15, 1.15); ax.set_ylim(-1.32, 1.15)
        ax.set_xticks([-1, 0, 1]); ax.set_yticks([-1, 0, 1])
        ax.tick_params(length=1.5, pad=1, labelsize=5.5, colors=MUTED)
        for sp in ax.spines.values():
            sp.set_visible(False)
    axes[0].set_ylabel("long. accel. / $\\mu g$", fontsize=6, color=MUTED, labelpad=1)
    axes[1].set_xlabel("lateral acceleration / $\\mu g$", fontsize=6, color=MUTED, labelpad=1)
    fig.subplots_adjust(left=0.1, right=0.995, top=0.84, bottom=0.17, wspace=0.08)
    fig.savefig("results/grip_use.png", dpi=200)
    fig.savefig("report/figs/grip_use.pdf", dpi=300)


if __name__ == "__main__":
    main()
