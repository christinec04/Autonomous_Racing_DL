"""50-race head-to-head (20 original + 30 extra race seeds) with confidence intervals -> results/headtohead50.md.

Races: results/eval_recover.json + results/final_v2_others.json (seeds 10000-10019) and results/eval_extra30.json
(seeds 10020-10049); all on the v2 simulator. Proportions get Wilson 95% intervals, comparisons Fisher's exact test
(finished, crashed) and Mann-Whitney U (passes, clean-lap time).
"""
import json
import numpy as np
from scipy.stats import fisher_exact, mannwhitneyu

FILES = ["results/eval_recover.json", "results/final_v2_others.json", "results/eval_extra30.json",
         "results/eval_residual_shield_s0.json", "results/eval_extra30_residual.json"]
CTRL = {"ppo_apf_rec@s0": "PPO + our shield + stall recovery (final)", "ppo_additive": "PPO + additive Eq. 2/3 shield",
        "pid_apf": "PID + APF", "ppo_residual_apf_rec@trained": "Residual PPO trained with our shield (E23)"}
OURS = "ppo_apf_rec@s0"


def wilson(k, n, z=1.96):
    if n == 0:
        return (np.nan, np.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


import pathlib
races = [r for f in FILES if pathlib.Path(f).exists() for r in json.load(open(f))["races"] if r["controller"] in CTRL]
keys = [(r["controller"], r["randomize"], r["seed"]) for r in races]
assert len(keys) == len(set(keys)), "duplicate races"
out = ["# Head-to-head on 50 race seeds per condition (v2 simulator)", "",
       "20 original + 30 extra race seeds (10000-10049), 5 laps, 3 opponents, DNF on first collision. "
       "Brackets: Wilson 95% interval. p-values vs ours: Fisher's exact test (finished, crashed), Mann-Whitney U "
       "(passes per race, clean-lap time). Generated by `python -m scripts.headtohead`.", ""]
for rz, cond in ((False, "nominal"), (True, "randomised")):
    out += [f"## {cond}", "", "| controller | races | finished | crashed | passes / race | clean lap (s) | "
            "p finished | p crashed | p passes | p lap |", "|---|---|---|---|---|---|---|---|---|---|"]
    by = {c: [r for r in races if r["controller"] == c and r["randomize"] == rz] for c in CTRL}
    def stats(R):
        fin = np.array([(not r["dnf"]) and len(r["lap_times"]) >= r.get("laps_target", 5) for r in R])
        cr = np.array([r["dnf"] for r in R])
        ps = np.array([r["overtake_successes"] for r in R])
        laps = np.array([t for r in R for t in r["lap_times"][1:]])
        return fin, cr, ps, laps
    so = stats(by[OURS])
    for c, name in CTRL.items():
        R = by[c]
        if not R:
            continue
        fin, cr, ps, laps = stats(R)
        n = len(R)
        lo, hi = wilson(fin.sum(), n); clo, chi = wilson(cr.sum(), n)
        row = (f"| {name} | {n} | {fin.sum()} ({lo:.0%}-{hi:.0%}) | {cr.sum()} ({clo:.0%}-{chi:.0%}) | "
               f"{ps.mean():.2f} | {laps.mean():.2f} |")
        if c == OURS:
            row += " - | - | - | - |"
        else:
            pf = fisher_exact([[so[0].sum(), len(so[0]) - so[0].sum()], [fin.sum(), n - fin.sum()]])[1]
            pc = fisher_exact([[so[1].sum(), len(so[1]) - so[1].sum()], [cr.sum(), n - cr.sum()]])[1]
            pp = mannwhitneyu(so[2], ps).pvalue
            pl = mannwhitneyu(so[3], laps).pvalue if len(laps) and len(so[3]) else np.nan
            row += f" {pf:.3g} | {pc:.3g} | {pp:.3g} | {pl:.3g} |"
        out.append(row)
    out.append("")
open("results/headtohead50.md", "w").write("\n".join(out))
print("\n".join(out))
