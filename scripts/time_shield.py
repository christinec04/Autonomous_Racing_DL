"""Wall-clock cost of the shield decision per control step (final controller, nominal race seeds).

Wraps env.shield and times every call; reports mean / p99 / max in ms and splits steps where the policy's action
passed the check from steps where the shield had to search blends or fallbacks. The control period is 40 ms.
usage: python -m scripts.time_shield [races=3]  -> results/shield_timing.md
"""
import sys, time
import numpy as np
from stable_baselines3 import PPO
from racing.env import RaceEnv, EnvConfig
from racing.shield import ShieldConfig
from racing.evaluate import SHIELD_FOR


class Timed:
    def __init__(self, sh):
        self.sh, self.t = sh, []

    def __call__(self, *a, **k):
        t0 = time.perf_counter()
        out = self.sh(*a, **k)
        self.t.append((time.perf_counter() - t0, out[1] > 0))
        return out

    def __getattr__(self, name):
        return getattr(self.sh, name)


def main(n=3):
    m = PPO.load("runs/ppo_residual_shield_s0/model_stage3.zip", device="cpu")
    T = []
    for seed in range(10000, 10000 + n):
        cfg = EnvConfig(n_opp=3, opp_speed=(0.5, 0.75), random_start=True, shield=ShieldConfig(**SHIELD_FOR["ppo_residual_apf_rec"]),
                        episode_time=200.0, seed=seed, tire="saturated_v2", recover=True, residual=True)
        env = RaceEnv(cfg)
        rng = np.random.default_rng(seed)
        opts = dict(s_ego=3.0, opp_gaps=list(np.cumsum(rng.uniform(5.0, 15.0, 3))), opp_speeds=list(rng.uniform(0.5, 0.75, 3)))
        obs, _ = env.reset(seed=seed, options=opts)
        env.shield = Timed(env.shield)
        while True:
            a, _ = m.predict(obs[None], deterministic=True)
            obs, r, te, tr, info = env.step(a[0])
            if te or tr:
                break
        T += env.shield.t[10:]  # skip warm-up (numba compilation on the first calls)
    t = np.array([x for x, _ in T]) * 1e3
    act = np.array([b for _, b in T])
    rows = [("all steps", t), ("action passed", t[~act]), ("shield intervened", t[act])]
    out = ["# Shield decision time per control step (final controller, one laptop core)", "",
           "Generated by `python -m scripts.time_shield`. Control period 40 ms (25 Hz).", "",
           "| steps | n | mean (ms) | p99 (ms) | max (ms) |", "|---|---|---|---|---|"]
    for name, x in rows:
        if len(x):
            out.append(f"| {name} | {len(x)} | {x.mean():.2f} | {np.percentile(x, 99):.2f} | {x.max():.2f} |")
    print("\n".join(out))
    open("results/shield_timing.md", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 3)
