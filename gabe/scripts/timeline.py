"""Chronological record of the project: every commit by day, with report snapshots and crashed or superseded runs.

Nothing is summarised away, so earlier attempts stay visible next to the ones that replaced them.
-> docs/timeline.md
"""
import pathlib
import subprocess
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    log = subprocess.run(["git", "log", "--reverse", "--date=format:%Y-%m-%d %H:%M", "--format=%h\t%ad\t%s"],
                         cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=True).stdout
    days = defaultdict(list)
    for line in log.splitlines():
        h, d, s = line.split("\t", 2)
        days[d[:10]].append((d[11:], h, s))
    snaps = defaultdict(list)
    for f in sorted((ROOT / "report" / "history").glob("midterm_*.pdf")):
        snaps[f.stem.split("_")[1]].append(f.name)
    crashed = sorted(p.name for p in (ROOT / "runs").iterdir() if p.is_dir() and ("crashed" in p.name or "attempt" in p.name))

    md = ["# Timeline", "",
          "Generated by `python -m scripts.timeline`. Every commit on this branch in order, so superseded results and "
          "abandoned attempts stay on record. Problems and how they were solved: [PROGRESS.md](../PROGRESS.md). "
          "Experiment write-ups: [experiments.md](experiments.md). Every training run: [RUNS.md](../RUNS.md). "
          "Commits before the Nov 6 squash: [presquash_history.md](presquash_history.md).", ""]
    if crashed:
        md += ["Interrupted or superseded run attempts kept in `runs/`: " + ", ".join(f"`{c}`" for c in crashed), ""]
    for day in sorted(days):
        md += [f"## {day} ({len(days[day])} commits)", ""]
        if snaps.get(day):
            md += ["Report versions: " + ", ".join(f"[{n[8:-4]}](../report/history/{n})" for n in snaps[day]), ""]
        md += [f"- {t} `{h}` {s}" for t, h, s in days[day]] + [""]
    (ROOT / "docs" / "timeline.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    print(f"{sum(map(len, days.values()))} commits over {len(days)} days")


if __name__ == "__main__":
    main()
