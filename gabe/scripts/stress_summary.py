"""E33 stress tests: races finished vs friction scale and vs number of opponents.

Friction 1.0 = the nominal races of the main protocol (same 20 race seeds, no lidar noise). Residual seeds are pooled
(mean of 3). Missing settings are skipped. -> results/stress.md, results/stress.png, report/figs/stress.pdf
"""
import json, pathlib
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

CTRL = {  # label -> (name, controllers pooled)
    "final": ("Residual + our shield (final)", ["ppo_residual_apf_rec@trained", "ppo_residual_apf_rec@trained_s1",
                                               "ppo_residual_apf_rec@trained_s2"]),
    "ppo": ("PPO + our shield (seed 0)", ["ppo_apf_rec@s0"]),
    "pid": ("PID + APF", ["pid_apf"]),
    "add": ("PPO + additive APF", ["ppo_additive"]),
}
COLOR = {"final": "#2a78d6", "ppo": "#d95f02", "pid": "#52514e", "add": "#9a9a9a"}
NOMINAL = ["results/eval_recover.json", "results/final_v2_others.json", "results/eval_residual_shield_s0.json",
           "results/eval_residual_shield_s1.json", "results/eval_residual_shield_s2.json"]


def finished(r):
    return not r["dnf"] and not r["stuck"]


def rate(races, ctrls):
    """mean over pooled controllers of the fraction finished (20 race seeds each)."""
    fr = [np.mean([finished(r) for r in races if r["controller"] == c]) for c in ctrls
          if any(r["controller"] == c for r in races)]
    return (float(np.mean(fr)), [float(f) for f in fr]) if fr else (None, [])


def load(f, rz=None):
    if not pathlib.Path(f).exists():
        return None
    R = json.load(open(f))["races"]
    return [r for r in R if rz is None or r["randomize"] == rz]


def main():
    nominal = [r for f in NOMINAL if (x := load(f, False)) for r in x if r["seed"] < 10020]
    mus, rows = [], {}
    for mu in (0.6, 0.7, 0.8, 1.0, 1.2, 1.3):
        R = nominal if mu == 1.0 else load(f"results/stress_mu{mu}.json")
        if not R:
            continue
        mus.append(mu)
        for k, (_, cs) in CTRL.items():
            rows.setdefault(k, []).append(rate(R, cs))
    opp = {}
    for n in (1, 3, 5):
        R = nominal if n == 3 else (load(f"results/stress_opp{n}_v2.json", False) or load(f"results/stress_opp{n}.json", False))
        if R:
            opp[n] = {k: rate(R, cs) for k, (_, cs) in CTRL.items()}
    oracle = {}
    for mu in (0.7, 0.8):
        R = load(f"results/stress_mu{mu}_oracle.json")
        if R:
            oracle[mu] = {k: rate(R, cs) for k, (_, cs) in CTRL.items() if k in ("final", "ppo")}

    md = ["# Stress tests (E33): fraction of 20 races finished", "",
          "Generated by `python -m scripts.stress_summary`. Training randomised friction over x0.85-1.15 with 3 opponents. "
          "Final controller: mean over 3 training seeds (per-seed values in brackets).", "",
          "| friction scale | " + " | ".join(CTRL[k][0] for k in CTRL) + " |", "|---" * (len(CTRL) + 1) + "|"]
    for i, mu in enumerate(mus):
        cells = []
        for k in CTRL:
            m, per = rows[k][i]
            cells.append("-" if m is None else f"{m:.0%}" + (f" ({', '.join(f'{x:.0%}' for x in per)})" if len(per) > 1 else ""))
        md.append(f"| x{mu} | " + " | ".join(cells) + " |")
    if opp:
        md += ["", "| opponents (nominal) | " + " | ".join(CTRL[k][0] for k in CTRL) + " |", "|---" * (len(CTRL) + 1) + "|"]
        for n, d in opp.items():
            md.append(f"| {n} | " + " | ".join("-" if d[k][0] is None else f"{d[k][0]:.0%}" for k in CTRL) + " |")
    if oracle:
        md += ["", "Shield predictor told the true friction (oracle, `--shield_mu`):", "",
               "| friction scale | final, nominal model | final, oracle | PPO + shield, nominal model | PPO + shield, oracle |",
               "|---|---|---|---|---|"]
        for mu, d in oracle.items():
            i = mus.index(mu)
            md.append(f"| x{mu} | {rows['final'][i][0]:.0%} | {d['final'][0]:.0%} | {rows['ppo'][i][0]:.0%} | {d['ppo'][0]:.0%} |")
    variants = [("nominal model", ""), ("true friction (oracle)", "_oracle"), ("estimate (E35)", "_muest"),
                ("smoother estimate (E35b)", "_mu2"), ("relaxed check + estimate (E36)", "_oxmu"),
                ("relaxed check + smoother estimate (E36b)", "_oxmu2"), ("E36b + median gate (E35c)", "_oxmu2med")]
    md += ["", "Final controller (E29 policies, 3 seeds) with each shield friction model, races finished of 60:", "",
           "| shield | x0.8 | x0.7 |", "|---|---|---|"]
    for name, suf in variants:
        cells = []
        for mu in (0.8, 0.7):
            R = load(f"results/stress_mu{mu}{suf}.json")
            R = [r for r in R if "residual" in r["controller"]] if R else None
            cells.append(f"{sum(not r['dnf'] and not r['stuck'] for r in R)} ({sum(r['wall'] for r in R)} wall)" if R else "-")
        md.append(f"| {name} | " + " | ".join(cells) + " |")
    open("results/stress.md", "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("\n".join(md))

    plt.rcParams.update({"font.size": 7, "font.family": "serif"})
    fig, ax = plt.subplots(figsize=(3.5, 1.7))
    ax.axvspan(0.85, 1.15, color="#ececea", lw=0, zorder=0)
    ax.text(1.0, 1.04, "training range", ha="center", va="bottom", fontsize=6, color="#52514e")
    for k, (name, _) in CTRL.items():
        y = [m for m, _ in rows[k]]
        ax.plot(mus, y, "-o", color=COLOR[k], lw=1.2 if k == "final" else 0.9, ms=3, label=name, zorder=3)
        if k == "final":
            lo = [min(p) for _, p in rows[k]]; hi = [max(p) for _, p in rows[k]]
            ax.fill_between(mus, lo, hi, color=COLOR[k], alpha=0.12, lw=0, zorder=2)
    ax.set_xlabel("friction scale ($\\mu$ / nominal)", fontsize=6.5)
    ax.set_ylabel("races finished", fontsize=6.5)
    ax.set_ylim(-0.03, 1.12); ax.set_yticks([0, 0.5, 1]); ax.set_yticklabels(["0%", "50%", "100%"])
    ax.set_xticks(mus)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    ax.tick_params(length=2, labelsize=6)
    ax.legend(fontsize=5.5, frameon=False, loc="lower right", handlelength=1.5)
    fig.subplots_adjust(left=0.13, right=0.99, top=0.93, bottom=0.2)
    fig.savefig("results/stress.png", dpi=200)
    fig.savefig("report/figs/stress.pdf")


if __name__ == "__main__":
    main()
