ABSTRACT_INTRO = r"""\begin{abstract}
We race a PPO agent against three PID and Pure Pursuit opponents in F1TENTH Gym, with an artificial potential
field (APF) acting as a safety shield that intervenes only when the agent's own action is predicted to cause a
crash. The full pipeline now runs end to end: track, opponents, classical baselines, shielded and unshielded PPO
with the three-stage curriculum, and a race-day evaluation with all six proposed metrics. Following the proposal
feedback, the shield is action-conditioned rather than additive, the simulator has friction-limited tyres, and
every metric has a target. On 50 shared race seeds our agent finishes 43 five-lap races (PID+APF: 28,
$p=0.002$), laps 8\,s faster than PID+APF and 12\,s faster than PPO with the proposal's additive shield,
crashes about 10$\times$ less often during training than unshielded PPO, and meets all six metric targets on the
20-race protocol. The main open problem is variance across training seeds, the focus of the rest of the semester.
\end{abstract}

\section{Introduction}
Classical racing controllers such as PID steering with an APF avoidance layer are safe but slow near obstacles and
cannot plan a pass; deep RL learns fast lines and tactics but crashes constantly while learning and gives no safety
guarantee. Our goal is to combine them: a PPO agent races, and an APF shield steps in only when a crash is
imminent, with a reward penalty for every intervention. The goal, track, opponents, reward and metrics are as
proposed.

\textbf{Updated scope.} Three changes, all prompted by the proposal feedback:
(1) The additive, clipped APF of the proposal's Eq.~2--3 cannot prevent violations, and its weight $w(d)$ ignores
the agent's action. We confirmed both experimentally (Sec.~\ref{sec:results}) and replaced it with an
\emph{action-conditioned} shield that simulates the agent's action and only intervenes if that action is predicted
unsafe; Eq.~2--3 is kept as a baseline. (2) Stock F1TENTH tyres have no grip limit (we measured 2.4\,g of lateral
acceleration at $\mu = 1.05$), so we added a friction-circle tyre model and traction control; this also makes the
``grip left over after cornering'' reach physically meaningful. (3) Every metric has a target, training
efficiency is measured with the shield removed, and crashes during training are reported, because a shield
trivially keeps laps clean.

\textbf{Contribution.} In ResRace~\cite{zhang2022} and RaceMOP~\cite{trumpp2024} the APF shapes every command; in
ours the policy drives and the APF acts only when an exact-model rollout of the policy's own action predicts a
collision or loss of control (3\% of race steps for training seed 0), with a fallback manoeuvre when no corrected
action is safe.

\textbf{What works now.} Everything in the proposal's plan through ``race day'': the Singapore-inspired track
(199\,m, 2.8\,m wide), three opponents, Pure Pursuit and PID+APF baselines, PPO with and without the shield on
three training seeds each, the four-car race evaluation (shared seeds, 5 laps, nominal and randomised), all six
metrics with targets and statistical tests, g-g and telemetry plots, and race videos. The code, a log of every
run and every problem we hit are in the team repository.

"""

